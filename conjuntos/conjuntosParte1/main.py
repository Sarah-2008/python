numeros = {1, 2, 3, 2, 1}
print(numeros) # {1, 2, 3} duplicatas sumidas

# Remover duplicatas de lista
lista = [1, 2, 2, 3, 3, 4]
print(set(lista))

# Operações
a = {1,2,3,4}
b = {3,4,5,6}
print(a | b) # união
print(a & a) #interseção (mostrar oq se repete)
print(a - b) # Diferença (o que "a" tem que "b" não tem)
print(a ^ b) # Diferença simétrica

